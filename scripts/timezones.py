def degrees(sign, digits):
    """ISO 6709 parts as zone.tab writes them: DDMM or DDMMSS (latitude), DDDMM or DDDMMSS (longitude)."""
    head = len(digits) - (4 if len(digits) in (6, 7) else 2)
    d, rest = int(digits[:head]), digits[head:]
    value = d + int(rest[:2]) / 60 + (int(rest[2:4]) / 3600 if len(rest) == 4 else 0)
    return round(-value if sign == '-' else value, 2)


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/zoneinfo/zone.tab'
    version_file = os.path.join(os.path.dirname(path), '+VERSION')
    version = open(version_file).read().strip() if os.path.exists(version_file) else 'unknown version'
    zones = {}
    for line in open(path, encoding='utf-8'):
        if line.startswith('#') or not line.strip():
            continue
        coords, name = line.split('\t')[1:3]
        m = re.fullmatch(r'([+-])(\d{4}|\d{6})([+-])(\d{5}|\d{7})', coords)
        if not m:
            sys.exit(f'unreadable coordinates for {name}: {coords}')
        zones[name.strip()] = [degrees(m.group(1), m.group(2)), degrees(m.group(3), m.group(4))]
    missing = sorted(a for a, z in ALIASES.items() if z not in zones)
    if missing:
        sys.exit('aliases pointing at zones not in zone.tab: ' + ', '.join(missing))
    out = sys.stdout
    out.write(f'// Generated by scripts/timezones.py from tzdb {version} zone.tab: don\'t edit by hand.\n')
    out.write('// Each time zone\'s reference city as [latitude, longitude] in degrees, north and east positive.\n')
    out.write('export const ZONES = {\n')
    for name in sorted(zones):
        out.write(f'  {json.dumps(name)}: {json.dumps(zones[name])},\n')
    out.write('};\n\n// older names some browsers still report, and the zone each one means\n')
    out.write('export const ALIASES = {\n')
    for name in sorted(ALIASES):
        out.write(f'  {json.dumps(name)}: {json.dumps(ALIASES[name])},\n')
    out.write('};\n')


if __name__ == '__main__':
    main()
